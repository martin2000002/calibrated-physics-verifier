"""ADR 0010 I5: the fit is closed-form, deterministic and grouped by video."""

from __future__ import annotations

import math
import tomllib

import numpy as np
import pytest

from physverify.sizing.fit import conformal_factor, fit_classes, fit_model, render_toml
from physverify.sizing.model import SizeModelTable
from physverify.sizing.samples import SizeSample


def synthetic_samples(seed: int = 3) -> list[SizeSample]:
    rng = np.random.default_rng(seed)
    out = []
    for label, mu in (("cup", math.log(0.09)), ("shoe", math.log(0.15))):
        for video in range(40):
            for _ in range(1 + video % 2):
                length = math.exp(rng.normal(mu, 0.2))
                out.append(SizeSample(label, f"{label}/batch-0/{video}", (length,) * 3, "train"))
    return out


def test_class_statistics_are_the_log_mean_and_sample_std() -> None:
    samples = synthetic_samples()
    fitted = fit_classes(samples)
    logs = np.log([s.extents[0] for s in samples if s.label == "cup"])
    assert fitted["cup"].mu_log == pytest.approx(logs.mean(), abs=1e-12)
    assert fitted["cup"].sigma_log == pytest.approx(logs.std(ddof=1), abs=1e-12)
    assert fitted["cup"].n_videos == 40 and fitted["cup"].n_objects == 60


def test_the_fit_writes_the_same_bytes_and_reads_back() -> None:
    samples = synthetic_samples()
    texts = [
        render_toml(fit_model(samples, folds=5, seed=0, coverage=0.683, source="t"))
        for _ in range(2)
    ]
    assert texts[0] == texts[1]
    assert texts[0].startswith("# generated by `physverify size fit`, do not edit")
    model = SizeModelTable.model_validate(tomllib.loads(texts[0])["size_model"])
    assert model == fit_model(samples, folds=5, seed=0, coverage=0.683, source="t")


def test_the_conformal_factor_hits_its_coverage_out_of_fold() -> None:
    samples = synthetic_samples()
    factor = conformal_factor(samples, folds=5, seed=0, coverage=0.683)
    assert 0.6 < factor < 1.6
    assert conformal_factor(samples, 5, 0, 0.954) > factor


def test_an_empty_model_is_the_committed_default() -> None:
    assert SizeModelTable().classes == {}
    assert SizeModelTable().estimated is True

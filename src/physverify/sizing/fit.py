"""Closed-form fit of the per-class log-normal and of its conformal sigma factor."""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

import numpy as np
from numpy.typing import NDArray

from physverify.sizing.model import ClassSize, SizeModelTable
from physverify.sizing.samples import SizeSample, log_lengths
from physverify.sizing.settings import SizingSettings
from physverify.stats.folds import grouped_folds

MIN_CLASS_OBJECTS = 2
HEADER = "# generated by `physverify size fit`, do not edit (ADR 0010).\n"


def fit_classes(samples: Sequence[SizeSample]) -> dict[str, ClassSize]:
    """Mean and sample standard deviation of log L per class (classes with < 2 objects dropped)."""
    logs = log_lengths(samples)
    labels = np.array([s.label for s in samples])
    fitted: dict[str, ClassSize] = {}
    for label in sorted(set(labels.tolist())):
        chosen = labels == label
        if int(chosen.sum()) < MIN_CLASS_OBJECTS:
            continue
        fitted[label] = ClassSize(
            mu_log=float(logs[chosen].mean()),
            sigma_log=float(logs[chosen].std(ddof=1)),
            n_objects=int(chosen.sum()),
            n_videos=len({s.video_id for s, c in zip(samples, chosen, strict=True) if c}),
        )
    return fitted


def standardized_residuals(
    train: Sequence[SizeSample], held_out: Sequence[SizeSample]
) -> NDArray[np.float64]:
    """|log L - mu_c| / sigma_c of ``held_out`` under classes fitted on ``train`` alone."""
    classes = fit_classes(train)
    usable = [s for s in held_out if s.label in classes and classes[s.label].sigma_log > 0]
    if not usable:
        return np.zeros(0)
    mu = np.array([classes[s.label].mu_log for s in usable])
    sigma = np.array([classes[s.label].sigma_log for s in usable])
    return np.asarray(np.abs(log_lengths(usable) - mu) / sigma, dtype=np.float64)


def conformal_factor(
    samples: Sequence[SizeSample], folds: int, seed: int, coverage: float
) -> float:
    """f such that ``coverage`` of the out-of-fold |r| / sigma_c is <= f (folds by video)."""
    ratios = [
        standardized_residuals(
            [s for s in samples if s.video_id not in fold],
            [s for s in samples if s.video_id in fold],
        )
        for fold in grouped_folds([s.video_id for s in samples], folds, seed)
    ]
    pooled = np.concatenate(ratios) if ratios else np.zeros(0)
    if pooled.size == 0:
        return 1.0
    return float(np.quantile(pooled, coverage, method="higher"))


def fit_model(
    samples: Sequence[SizeSample], *, folds: int, seed: int, coverage: float, source: str
) -> SizeModelTable:
    return SizeModelTable(
        source=source,
        sigma_factor=conformal_factor(samples, folds, seed, coverage),
        coverage_target=coverage,
        classes=fit_classes(samples),
    )


def render_toml(model: SizeModelTable) -> str:
    """Deterministic TOML of ``[size_model]`` (floats as their shortest repr)."""
    lines = [
        HEADER.rstrip("\n"),
        "[size_model]",
        f"source = {_string(model.source)}",
        "estimated = true",
        f"sigma_factor = {model.sigma_factor!r}",
        f"coverage_target = {model.coverage_target!r}",
    ]
    for label, size in sorted(model.classes.items()):
        lines += [
            "",
            f"[size_model.classes.{label}]",
            f"mu_log = {size.mu_log!r}",
            f"sigma_log = {size.sigma_log!r}",
            f"n_objects = {size.n_objects}",
            f"n_videos = {size.n_videos}",
        ]
    return "\n".join(lines) + "\n"


def _string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def fit_record(
    model: SizeModelTable, train: Sequence[SizeSample], sizing: SizingSettings
) -> dict[str, Any]:
    """Fit evidence; the test sigma is measured by ``size eval`` (eval.json), never here."""
    return {
        "estimated": True,
        "model": model.model_dump(mode="json"),
        "n_objects": len(train),
        "n_videos": len({s.video_id for s in train}),
        "folds": sizing.folds,
        "factor_at_coverage": {
            str(q): conformal_factor(train, sizing.folds, sizing.seed, q) for q in (0.683, 0.954)
        },
        "test_sigma": "see eval.json (size eval)",
        "truth_limit": "box sizes come from ARKit; their own error is not documented",
    }
